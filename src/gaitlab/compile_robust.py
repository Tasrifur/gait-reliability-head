"""Summarise results/robust_baselines_<ds>.json -> results/robust_baselines_summary.md.

Per scenario: rank-1 averaged over probe conditions, mean +- std over seeds, per scorer;
'head - best baseline' is paired per seed against the best of b1/median/energy/head_global.

Usage: python -m gaitlab.compile_robust
"""
import json
import os

import numpy as np

from .robust_baselines import SCORERS

OURS = ['head', 'hybrid']
BASE = [k for k in SCORERS if k not in OURS]
NAMES = {'b1': 'mean (B1)', 'median': 'median proto', 'energy': 'energy mask',
         'head_global': 'head, pooled var', 'head': 'head (ours)', 'hybrid': 'head + energy prior'}


def main():
    lines = ['# Robustness baselines vs the reliability head (rank-1 %, mean over probe conditions; '
             'mean ± std over seeds)', '',
             'Generated by `python -m gaitlab.compile_robust` from `results/robust_baselines_*.json`.', '']
    for ds in ['casiab', 'casiae', 'oumvlp']:
        path = f'results/robust_baselines_{ds}.json'
        if not os.path.exists(path):
            continue
        res = json.load(open(path))
        seeds = sorted(res)
        scen = sorted({k.split('>')[0] for k in res[seeds[0]]['acc']},
                      key=lambda s: ['fgcv', 'corrupt_enroll', 'occ_hband', 'occ_vband', 'occ_bottom',
                                     'occ_noise'].index(s))
        rules = '; '.join(f'{k}: ' + ', '.join(res[s]['energy_rule'][k] for s in seeds)
                          for k in res[seeds[0]]['energy_rule'])
        lines += [f'## {ds} ({len(seeds)} seeds; energy rules chosen on calibration ids — {rules})', '',
                  '| scenario | ' + ' | '.join(NAMES[k] for k in SCORERS) +
                  ''.join(f' | {NAMES[o]} − best baseline (wins)' for o in OURS) + ' |',
                  '|---|' + '---|' * (len(SCORERS) + len(OURS))]
        for sc in scen:
            per = {k: np.array([np.mean([v[k] for c, v in res[s]['acc'].items() if c.split('>')[0] == sc])
                                for s in seeds]) for k in SCORERS}
            best = max(BASE, key=lambda k: per[k].mean())
            cells = [f'{per[k].mean():.1f} ± {per[k].std():.1f}' for k in SCORERS]
            mx = max(SCORERS, key=lambda k: per[k].mean())
            cells[SCORERS.index(mx)] = f'**{cells[SCORERS.index(mx)]}**'
            for o in OURS:
                diff = per[o] - per[best]
                cells.append(f'{diff.mean():+.1f} vs {NAMES[best]} ({int((diff > 0).sum())}/{len(seeds)})')
            lines.append(f'| {sc} | ' + ' | '.join(cells) + ' |')
        lines.append('')
    with open('results/robust_baselines_summary.md', 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
